"""
The rise layers of the first launch: what a garden picture adds to the picture of an earlier
stage, alone, at the full size of the pictures (1170 x 816), so that it lies exactly over them.
The first launch (src/features/onboarding) lifts this layer from the ground as a new stage of the
story arrives, before the whole picture settles on top (the owner's chosen prototype,
docs/design/premier-lancement-voix/index.html, `new-hNN-f0`).

    python3 -I tools/garden-pictures/rise-layers.py

Reads the shipped pictures (assets/images/garden/level-1/base) and writes
assets/images/garden/level-1/rise/new-hNN-f0.webp and src/features/garden/garden-rise.generated.ts.
Needs Pillow, like pixels.py and growth-sprites.py (a tool of the person who regenerates, not a
dependency of the app). The pictures are the project's CC0 renders (assets/images/garden/NOTICE.txt):
these layers are cut from them and carry the same provenance.
"""

import os

from PIL import Image, ImageChops, ImageFilter

TOOL = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(TOOL))
BASE = os.path.join(REPO, "assets", "images", "garden", "level-1", "base")
OUT = os.path.join(REPO, "assets", "images", "garden", "level-1", "rise")
TABLE = os.path.join(REPO, "src", "features", "garden", "garden-rise.generated.ts")

# The stages of the story, each with the stage before it (the prototype's `from`).
STAGES = ((0, 8), (8, 20), (20, 30), (30, 40), (40, 60))
# A change smaller than this (sum over the four channels) is the noise of the lossy pictures:
# the value growth-sprites.py uses on the same set.
THRESHOLD = 40
QUALITY = 84


def rise_layer(before: Image.Image, after: Image.Image) -> Image.Image:
    """The pixels of `after` that differ from `before`, everything else transparent."""
    diff = ImageChops.difference(before, after)
    r, g, b, a = diff.split()
    summed = ImageChops.add(ImageChops.add(r, g), ImageChops.add(b, a))
    mask = summed.point(lambda value: 255 if value > THRESHOLD else 0)
    # Close the small holes, drop the specks, then soften the edge by a pixel (as growth-sprites.py).
    mask = mask.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(5))
    mask = mask.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.MaxFilter(3))
    mask = mask.filter(ImageFilter.GaussianBlur(0.8))
    layer = after.copy()
    layer.putalpha(ImageChops.multiply(after.getchannel("A"), mask))
    return layer


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    names = []
    for start, end in STAGES:
        before = Image.open(os.path.join(BASE, f"h{start:02d}-f0.webp")).convert("RGBA")
        after = Image.open(os.path.join(BASE, f"h{end:02d}-f0.webp")).convert("RGBA")
        if before.size != after.size:
            raise SystemExit(f"h{start:02d}-f0 and h{end:02d}-f0 differ in size")
        name = f"new-h{end:02d}-f0"
        rise_layer(before, after).save(os.path.join(OUT, f"{name}.webp"), "WEBP", quality=QUALITY, method=6)
        names.append((end, name))
    lines = [
        "/* generated by tools/garden-pictures/rise-layers.py: do not edit by hand. */",
        "/**",
        " * What each stage of the first launch's story adds to the stage before it, alone, at the size",
        " * of the garden pictures (docs/design/premier-lancement-voix/index.html, `new-hNN-f0`).",
        " */",
        "export const GARDEN_RISE_ASSETS: Readonly<Record<number, number>> = {",
    ]
    for end, name in names:
        lines.append(f"  {end}: require('../../../assets/images/garden/level-1/rise/{name}.webp'),")
    lines.append("};")
    with open(TABLE, "w", encoding="utf-8") as table:
        table.write("\n".join(lines) + "\n")
    print(f"wrote {len(names)} rise layers to {OUT}")


if __name__ == "__main__":
    main()
