/**
 * Writes src/domain/sun/zone-coordinates.ts: where each time zone of the IANA time zone database
 * is, so that the app can place the sun without asking where the person is (docs/DECISIONS.md
 * D51). Public domain data (see NOTICE.txt beside this file).
 *
 *   node tools/sun-zones/build.mjs [--zoneinfo <folder>] [--verify]
 *
 * The folder holds the database's zone.tab, zone1970.tab and tzdata.zi (Ubuntu's `tzdata`
 * package installs them in /usr/share/zoneinfo). A zone takes the coordinates of its own line in
 * zone.tab (one line per country and zone, so Arctic/Longyearbyen is not Oslo), else of
 * zone1970.tab; a link (`L target name` in tzdata.zi, such as Asia/Calcutta) takes those of the
 * zone it points to. Zones without a place (Etc/UTC, EST5EDT…) are left out: the app then
 * estimates the place from the UTC offset. Deterministic: two runs give the same file.
 * `--verify` only checks that the committed file is what the build writes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUTPUT = join(ROOT, 'src', 'domain', 'sun', 'zone-coordinates.ts');
/** Two decimals of a degree: about a kilometre, far finer than a time zone's spread. */
const DECIMALS = 100;
/** `+DDMM+DDDMM` or `+DDMMSS+DDDMMSS`, as zone.tab writes a place. */
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const ISO6709 = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/;

function fail(message) {
  console.error(`sun-zones: ${message}`);
  process.exit(1);
}

function degrees(sign, whole, minutes, seconds) {
  const value = Number(whole) + Number(minutes) / 60 + Number(seconds ?? 0) / 3600;
  return Math.round((sign === '-' ? -value : value) * DECIMALS) / DECIMALS;
}

function parsePlace(text, zone) {
  const match = ISO6709.exec(text);
  if (match === null) fail(`cannot read the place "${text}" of ${zone}`);
  const [, latSign, latDeg, latMin, latSec, lonSign, lonDeg, lonMin, lonSec] = match;
  return [degrees(latSign, latDeg, latMin, latSec), degrees(lonSign, lonDeg, lonMin, lonSec)];
}

/** Zone → [latitude, longitude] from a `.tab` file (country codes, place, zone, comment). */
function readTab(path) {
  const places = new Map();
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    if (line.trim() === '' || line.startsWith('#')) continue;
    const [, place, zone] = line.split('\t');
    if (place === undefined || zone === undefined) fail(`unexpected line in ${path}: ${line}`);
    places.set(zone, parsePlace(place, zone));
  }
  return places;
}

/** Link name → target zone, from the `L target name` lines of tzdata.zi. */
function readLinks(path) {
  const links = new Map();
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    if (!line.startsWith('L ')) continue;
    const [, target, name] = line.split(' ');
    links.set(name, target);
  }
  return links;
}

function readVersion(path) {
  const match = /^# version (\S+)/m.exec(readFileSync(path, 'utf8'));
  if (match === null) fail(`no version line in ${path}`);
  return match[1];
}

function build(zoneinfo) {
  const own = readTab(join(zoneinfo, 'zone.tab'));
  const shared = readTab(join(zoneinfo, 'zone1970.tab'));
  const links = readLinks(join(zoneinfo, 'tzdata.zi'));
  const version = readVersion(join(zoneinfo, 'tzdata.zi'));

  const places = new Map(own);
  for (const [zone, place] of shared) if (!places.has(zone)) places.set(zone, place);
  for (const [name, target] of links) {
    if (places.has(name)) continue;
    let zone = target;
    // A link may point to another link; the database keeps chains short, but follow them.
    for (let hops = 0; links.has(zone) && hops < links.size; hops += 1) zone = links.get(zone);
    const place = places.get(zone) ?? own.get(zone) ?? shared.get(zone);
    if (place !== undefined) places.set(name, place);
  }

  const lines = [...places.keys()]
    .sort()
    // Quoted only where a key needs it (Cuba, GB… do not), as Prettier writes it.
    .map((zone) => {
      const key = IDENTIFIER.test(zone) ? zone : `'${zone}'`;
      return `  ${key}: [${places.get(zone).join(', ')}],`;
    });
  return `/**
 * Where each time zone is (latitude, longitude in degrees, north and east positive). Generated by
 * tools/sun-zones/build.mjs from the IANA time zone database ${version} (zone.tab, zone1970.tab
 * and the links of tzdata.zi; public domain, tools/sun-zones/NOTICE.txt). Do not edit by hand.
 */
export const ZONE_COORDINATES: Readonly<Record<string, readonly [number, number]>> = {
${lines.join('\n')}
};
`;
}

const { values } = parseArgs({
  options: {
    zoneinfo: { type: 'string', default: '/usr/share/zoneinfo' },
    verify: { type: 'boolean', default: false },
  },
});
const text = build(values.zoneinfo);
if (values.verify) {
  if (readFileSync(OUTPUT, 'utf8') !== text) fail(`${OUTPUT} is not what the build writes`);
  console.log('sun-zones: up to date');
} else {
  writeFileSync(OUTPUT, text);
  console.log(`sun-zones: wrote ${text.split('\n').length} lines to ${OUTPUT}`);
}
